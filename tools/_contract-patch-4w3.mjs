// 契约补丁：在 §4w2 之后插入「键必须是唯一标识，不是可读标识」。
import { readFileSync, writeFileSync } from 'node:fs';
const P = 'C:/WorkSpace/Bannerlord/BannerlordCode.github.io/CONTRACT.md';
let t = readFileSync(P, 'utf8');
if (t.includes('键必须是唯一标识')) { console.log('已存在，跳过'); process.exit(0); }

const anchor = '## 4x. 自查发现量具范围有误';
if (!t.includes(anchor)) { console.error('找不到锚点 §4x'); process.exit(1); }

const block = `## 4w3. ★ 键必须是【唯一标识】，不是【可读标识】（boss #7162 定稿）

\`\`\`
凡台账 / 清单 / 索引 / 快照 / 交叉引用的键，必须是【唯一标识】。
可读的键几乎总是短的，而短的键几乎总是不唯一。
⇒ 本仓唯一无歧义的键 = 【完整仓库相对路径】
\`\`\`

**实测（本仓，lead-6 量）**：
\`\`\`
全树 7,166 个不同页名，其中 7,165 个都出现 >1 次
  AutoGeneratedSaveManager.md × 22   （跨版本 × 语言 × 多个桶）
  MetaDataExtensions.md × 15 · Crafting.md × 14 · EventManager.md × 14
\`\`\`
**⇒ 桶之上还有【版本】与【语言】两层 ⇒「桶 + 页名」也不解决任何问题。**

**本会话我踩了同一个坑三次，每次形状不同、机制相同**：
\`\`\`
① 类型名  用「文件名去 .md」当类型名  → 撞上把命名空间编进文件名的页（ItemComparerBase__TaleWorlds_…）
② 桶+页名                        → 跨版本 / 跨语言重名，台账错位、快照撞页
③ 「同一个名字在树里唯一」        → 两把尺都默认它唯一，包括我自己新写的台账
\`\`\`
**共同根因：给尺喂了一个不唯一的键，而尺不报错 —— 它只会安静地查到另一个对象。**

**⇒ 与 §4r 同源**：§4r 要求清单带完整相对路径；
本条把它提升为「凡键皆如此」，并说明**为什么短键不可用**。

**⇒ 判断一个键是否合格的一句话**：
\`\`\`
把这个键在全树 grep 一次，命中 >1 ⇒ 它不合格，无论它多可读。
\`\`\`

`;

t = t.replace(anchor, block + anchor);
writeFileSync(P, t, 'utf8');
console.log('已插入 §4w3。新行数 = ' + t.split(/\r?\n/).length);
