// tools/_verify/lead-20/nav-up-link-gap.mjs  —  READ-ONLY
// Emits nav-up-link-gap.tsv: every page with NO link back to its parent section index,
// with its H2 headings and the missing-return-path fact.
//
// Caliber (must be stated with any number derived from this):
//   A page has a return path iff some markdown link target matches ^(\.\./)+(_index\.md)?$
//   OR is the bare ".." — the bare form IS accepted because tools/audit-links.mjs line 77
//   normalises ".." to climb from the page folder. Rejecting ".." over-counts by exactly 87
//   pages that do have a working return path (measured 2026-10-07: strict 870 vs aligned 783).
//
// This is NOT the orphan caliber. nav-orphans.mjs asks "does anything link IN"
// (caliber self-link-counts-as-inbound); this asks "can a reader get back OUT".
//
// Usage: node tools/_verify/lead-20/nav-up-link-gap.mjs [out.tsv]
import fs from 'fs';
import path from 'path';

const CONTENT = 'content';
const OUT = process.argv[2] || 'tools/_verify/lead-20/nav-up-link-gap.tsv';

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.md')) files.push(p);
  }
})(CONTENT);

const LINK = /\[[^\]]*\]\(([^)\s]+)\)/g;
const UP = /^(\.\.\/)+(_index\.md)?$/;
const BARE = '..';

const rows = [];
let total = 0, leaf = 0;

for (const f of files) {
  const rel = f.split(path.sep).join('/');
  const base = path.basename(rel);
  total++;
  const isIndex = base === '_index.md';
  if (!isIndex) leaf++;

  const raw = fs.readFileSync(f, 'utf8');
  const body = raw.replace(/^---[\s\S]*?\n---\n/, '');

  let hasUp = false, m;
  LINK.lastIndex = 0;
  while ((m = LINK.exec(body))) { const t = m[1]; if (UP.test(t) || t === BARE) { hasUp = true; break; } }
  if (hasUp) continue;

  const h2 = body.split('\n').filter(l => /^##\s+\S/.test(l)).map(l => l.replace(/^##\s+/, '').trim());
  const isNav = h2.some(h => /^(导航|Navigation)$/i.test(h));

  rows.push([
    rel,
    isIndex ? 'section_index' : 'leaf',
    String(h2.length),
    isNav ? 'has_导航' : 'NO_导航',
    h2.join(' / ') || '(no H2 headings)',
  ]);
}

const header = [
  '# nav-up-link-gap.tsv — pages with NO link back to their parent section index',
  '# caliber: no markdown link target matching ^(\\.\\./)+(_index\\.md)?$ and not the bare ".."',
  '#   (bare ".." accepted because tools/audit-links.mjs line 77 normalises it to climb)',
  '# NOT the orphan caliber: these pages DO have inbound links; they lack a RETURN path.',
  '# generated by tools/_verify/lead-20/nav-up-link-gap.mjs',
  '# columns: path<TAB>kind<TAB>h2_count<TAB>nav_section<TAB>h2_list',
].join('\n');

fs.writeFileSync(OUT, header + '\n' + rows.map(r => r.join('\t')).join('\n') + '\n');

console.log('TOTAL_PAGES=' + total);
console.log('LEAF_PAGES=' + leaf);
console.log('NO_UP_LINK=' + rows.length);
console.log('NO_UP_LINK_LEAF=' + rows.filter(r => r[1] === 'leaf').length);
console.log('OF_THOSE_WITH_导航_SECTION=' + rows.filter(r => r[3] === 'has_导航').length);
console.log('WRITTEN=' + OUT + '  data_rows=' + rows.length);
