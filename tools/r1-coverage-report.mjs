// r1-coverage-report.mjs
//
// Machine-readable R1 coverage gate (H0 / H10):
//   public business types − (deep_pass page OR handwritten family purpose entry)
//   = remaining gap
//
// Inventory-only tool. Does NOT rewrite any content/** markdown.
//
// Usage (from repo root):
//   node tools/r1-coverage-report.mjs
//   node tools/r1-coverage-report.mjs --version 1.3.15 --lang zh
//   node tools/r1-coverage-report.mjs --api-root content/v1.3.15/zh/api
//
// Inputs:
//   tools/data/type-inventory.json
//   tools/data/s-tier.json
//   content pages under api root (classified inline; same rules as handwritten-coverage.mjs)
//
// Output:
//   tools/data/r1-coverage-report.json
//   stdout summary counts + top gap namespace prefixes

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, relative, dirname, basename, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DATA_DIR = join(ROOT, 'tools', 'data');
const OUT_JSON = join(DATA_DIR, 'r1-coverage-report.json');

const args = process.argv.slice(2);
function argValue(flag, fallback) {
  const i = args.indexOf(flag);
  if (i >= 0 && args[i + 1]) return args[i + 1];
  return fallback;
}

const VERSION = argValue('--version', '1.3.15');
const LANG = argValue('--lang', 'zh');
const API_ROOT_REL = argValue('--api-root', `content/v${VERSION}/${LANG}/api`);
const GAP_SAMPLE_SIZE = Number(argValue('--gap-sample', '50')) || 50;

const apiRoot = join(ROOT, API_ROOT_REL);
const reSep = new RegExp(sep === '\\' ? '\\\\' : sep, 'g');

function rel(p) {
  return relative(ROOT, p).replace(reSep, '/');
}

// ---------------------------------------------------------------------------
// Noise filter (align with generate-inventory.mjs + doc-contract platform noise)
// Inventory already strips most of this; re-apply so report stays correct if
// inventory ever includes residual third-party / platform glue.
//
// Two layers for R1 (SP mod deep-body target):
//   1) Base platform noise — never in business inventory counts
//   2) R1-extra noise — still listable as inventory business meta, but OUT of
//      r1Target denominator (multiplayer message spam, music engine, pure IMB*)
// Never treat CampaignSystem / MountAndBlade core gameplay namespaces as noise.
// ---------------------------------------------------------------------------
const NOISE_PREFIX =
  /^(Steamworks|Galaxy|GalaxyCSharp|Newtonsoft|System|jose|JetBrains|Harmony|Mono|Microsoft|Alex|nunit|Xceed|LiteDB|MessagePack|ZeroMQ|Razor|Selenium|Cef|WebDriver|Svg|Ookii|NLog|Custom|ManagedCallbacks|FxResources|Security)(\.|$)/i;

/** Base platform / third-party noise (not inventory business). */
function isBaseNoiseNamespace(ns) {
  if (!ns) return false;
  if (NOISE_PREFIX.test(ns)) return true;
  const segs = ns.split('.');
  for (const s of segs) {
    if (s === 'CodeGenerator' || s === 'GeneratedMessages') return true;
    if (/^AutoGenerated\d*$/.test(s)) return true;
  }
  // Platform service glue (doc-contract: platform noise → inventory only, not R1 body target)
  if (/^TaleWorlds\.PlatformService(\.|$)/i.test(ns)) return true;
  if (/^TaleWorlds\.PlayerServices(\.|$)/i.test(ns)) return true;
  if (/^TaleWorlds\.Diamond(\.|$)/i.test(ns)) return true;
  if (/^TaleWorlds\.ServiceDiscovery(\.|$)/i.test(ns)) return true;
  return false;
}

/**
 * R1-extra noise: multiplayer/network message spam + music engine.
 * Still inventory-listable; excluded from r1Target deep-body denominator only.
 * Does NOT blanket-exclude TaleWorlds.CampaignSystem / MountAndBlade.
 */
function isR1ExtraNoiseNamespace(ns) {
  if (!ns) return false;
  // NetworkMessages.* (MP mission net messages)
  if (/^NetworkMessages(\.|$)/i.test(ns)) return true;
  // Messages.From* / Messages.To* / Messages.BattleServer* diamond MP traffic
  if (/^Messages\.(From|To)/i.test(ns)) return true;
  if (/^Messages\.BattleServer/i.test(ns)) return true;
  if (/^Messages\.CustomBattleServer/i.test(ns)) return true;
  if (/^Messages\.Lobby/i.test(ns)) return true;
  // Remaining Messages.* roots are MP diamond protocol (not SP Campaign messages)
  if (/^Messages(\.|$)/i.test(ns)) return true;
  // Top-level BattleServer* / CustomBattleServer* / Lobby* (if any)
  if (/^BattleServer/i.test(ns)) return true;
  if (/^CustomBattleServer/i.test(ns)) return true;
  if (/^Lobby(\.|$)/i.test(ns)) return true;
  // psai.* adaptive music engine — not SP mod API surface
  if (/^psai(\.|$)/i.test(ns)) return true;
  // Diamond multiplayer matchmaking / lobby stack (noise-policy: inventory-only)
  if (/\.Diamond(\.|$)/i.test(ns) || /^TaleWorlds\.MountAndBlade\.Diamond(\.|$)/i.test(ns)) {
    return true;
  }
  // Platform achievement / activity / avatar services (not SP campaign API)
  if (/^TaleWorlds\.AchievementSystem(\.|$)/i.test(ns)) return true;
  if (/^TaleWorlds\.ActivitySystem(\.|$)/i.test(ns)) return true;
  if (/^TaleWorlds\.Avatar(\.|$)/i.test(ns)) return true;
  // Explicit multiplayer module roots (noise-policy Multiplayer*)
  if (/^TaleWorlds\.MountAndBlade\.Multiplayer(\.|$)/i.test(ns)) return true;
  if (/^SandBox\.Multiplayer(\.|$)/i.test(ns)) return true;
  if (/^Multiplayer(\.|$)/i.test(ns)) return true;
  return false;
}

function isBaseNoiseTypeName(name) {
  if (!name) return false;
  if (/AutoGenerated|Newtonsoft|Steamworks/i.test(name)) return true;
  return false;
}

/**
 * R1-extra type-name noise (noise-policy + MP server glue).
 * Pure IMB* = native interop thin wrappers (inventory only, not R1 deep body).
 * BattleServer* / CustomBattleServer* / Lobby* type names when not already
 * caught by namespace (e.g. residual under other roots).
 */
function isR1ExtraNoiseTypeName(name) {
  if (!name) return false;
  // Pure native interop thin wrappers (noise-policy IMB*)
  if (/^IMB[A-Z]/.test(name)) return true;
  if (/^BattleServer/i.test(name)) return true;
  if (/^CustomBattleServer/i.test(name)) return true;
  // Lobby* multiplayer lobby protocol types (not Campaign lobby menus)
  if (/^Lobby[A-Z]/.test(name) || /^Lobby$/i.test(name)) return true;
  return false;
}

/** Combined noise for inventory-business filtering (base + R1-extra). */
function isNoiseNamespace(ns) {
  return isBaseNoiseNamespace(ns) || isR1ExtraNoiseNamespace(ns);
}

function isNoiseTypeName(name) {
  return isBaseNoiseTypeName(name) || isR1ExtraNoiseTypeName(name);
}

