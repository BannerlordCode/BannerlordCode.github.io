const FORMULAIC_PURPOSE = [
  /是\s+[\w.]+\s+(?:下|中)的公开类型/u,
  /is a public (?:TaleWorlds\s+)?type\b/iu,
  /is a public type (?:in|under)\s+/iu,
  /公开类型[。.]?\s*$/u,
  /提供可重写[（(]override\/virtual[）)]的定制点/u,
  /^[\w.`]+$/,
  /^-+$/,
  /^用途$/,
  /^Purpose$/i,
  /^类$/,
  /^类型$/,
  /^Type$/i,
  /^典型时机$/,
  /^说明$/,
  /^备注$/,
  /^深页$/,
  /^已写$/,
  /^簇页用途句$/,
];

const TYPE_TOKEN_RE = /(?:\[`?([A-Za-z_][\w]*)`?\]\([^)]+\)|`([A-Za-z_][\w]*)`|\b([A-Z][A-Za-z0-9_]{1,80})\b)/g;

function extractTypeTokens(cell) {
  const names = new Set();
  if (!cell) return names;
  let m;
  const re = new RegExp(TYPE_TOKEN_RE.source, 'g');
  while ((m = re.exec(cell))) {
    // m[1] = markdown link text, m[2] = backtick code, m[3] = bare PascalCase word
    const fromLink = !!(m[1] || m[2]);
    const n = m[1] || m[2] || m[3];
    if (!n) continue;
    // Skip obvious non-type table *header labels* only when bare (not [Module](…) links).
    // Real inventory types named Module / Type must count when linked.
    if (
      !fromLink &&
      /^(Namespace|Module|Type|Class|枚举|类|接口|结构|用途|时机|说明|备注|问题|答案|维度|事实|何时|与|这是什么)$/i.test(
        n
      )
    ) {
      continue;
    }
    // Prefer PascalCase / IInterface; allow linked lowercase inventory names (e.g. bin)
    if (!/^[A-Z]/.test(n)) {
      if (!(fromLink && n.length >= 2 && /^[a-z][A-Za-z0-9_]*$/.test(n))) continue;
    }
    if (n.length < 2) continue;
    names.add(n);
  }
  return names;
}

function isNonEmptyPurpose(raw, typeName) {
  if (raw == null) return false;
  let s = String(raw).trim();
  if (!s) return false;
  // Strip markdown link wrappers for length check
  s = s
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/[`*]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (s.length < 6) return false;
  if (typeName && (s === typeName || s === `${typeName}.`)) return false;
  for (const re of FORMULAIC_PURPOSE) {
    if (re.test(s)) return false;
  }
  // Cell that is only more type links → not a purpose
  const withoutTypes = s
    .replace(/\b[A-Z][A-Za-z0-9_]{1,80}\b/g, '')
    .replace(/[,;/|、，。\s]+/g, '')
    .trim();
  if (!withoutTypes) return false;
  return true;
}

/**
 * Collect type names that have a non-empty purpose cell / 用途 line
 * inside a family_entry_pass _index body.
 */
function extractFamilyCoveredTypes(text, pagePath) {
  const covered = new Map(); // typeName -> { path, purposeSnippet }

  const lines = text.split(/\r?\n/);
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li];

    // Table rows
    if (/^\|/.test(line) && !/^\|\s*[-:\s|]+\s*\|/.test(line)) {
      const cells = line
        .split('|')
        .slice(1, -1)
        .map((c) => c.trim());
      if (cells.length < 2) continue;
      // Skip pure header rows (用途 / 类 / Type)
      const joined = cells.join(' ');
      if (/^(类|类型|Type|Class|用途|Purpose|说明|备注|典型时机)\b/i.test(cells[0]) && cells.every((c) => c.length < 24)) {
        continue;
      }

      for (let i = 0; i < cells.length; i++) {
        const names = extractTypeTokens(cells[i]);
        if (!names.size) continue;
        // Purpose candidates: other cells that are not pure type-link cells
        for (const name of names) {
          let purpose = null;
          for (let j = 0; j < cells.length; j++) {
            if (j === i) continue;
            if (isNonEmptyPurpose(cells[j], name)) {
              purpose = cells[j];
              break;
            }
          }
          // Decision-table style: first cell is intent (purpose), later cells hold type links
          if (!purpose && i > 0 && isNonEmptyPurpose(cells[0], name)) {
            purpose = cells[0];
          }
          if (purpose) {
            covered.set(name, {
              path: pagePath,
              purposeSnippet: stripMdNoise(purpose).slice(0, 120),
            });
          }
        }
      }
      continue;
    }

    // List / prose: - [TypeName](url) — purpose   OR  **TypeName**：用途
    const listType =
      line.match(
        /^\s*[-*]\s+\[`?([A-Za-z_][\w]*)`?\]\([^)]+\)\s*[:：—–-]\s*(.+)$/
      ) ||
      line.match(/^\s*[-*]\s+\*\*`?([A-Za-z_][\w]*)`?\*\*\s*[:：—–-]\s*(.+)$/) ||
      line.match(/^\s*[-*]\s+`([A-Za-z_][\w]*)`\s*[:：—–-]\s*(.+)$/);
    if (listType) {
      const name = listType[1];
      const purpose = listType[2];
      if (/^[A-Z]/.test(name) && isNonEmptyPurpose(purpose, name)) {
        covered.set(name, {
          path: pagePath,
          purposeSnippet: stripMdNoise(purpose).slice(0, 120),
        });
      }
      continue;
    }

    // 用途 line near a type mention on same or previous line
    const purposeLine = line.match(/(?:\*\*)?用途(?:\s*\/\s*Purpose)?(?:\*\*)?\s*[:：]\s*(.+)$/i);
    if (purposeLine && isNonEmptyPurpose(purposeLine[1], null)) {
      const window = [lines[li - 1] || '', line, lines[li + 1] || ''].join(' ');
      for (const name of extractTypeTokens(window)) {
        if (isNonEmptyPurpose(purposeLine[1], name)) {
          covered.set(name, {
            path: pagePath,
            purposeSnippet: stripMdNoise(purposeLine[1]).slice(0, 120),
          });
        }
      }
    }
  }

  return covered;
}

